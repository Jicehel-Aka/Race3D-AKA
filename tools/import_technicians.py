#!/usr/bin/env python3
"""Imports the pit crew technician sheet (6 frames on a magenta background) into main/game/tech_art.cpp/.h.

Usage:  python3 tools/import_technicians.py tools/technician_sheet.png main/game
Frames (left to right): idle, walk A, walk B, kneeling with wrench, carrying a tyre, arm raised. Figures face right.
Needs Pillow and numpy.  The result is 15 colours + transparent, in the AKA native pixel format (R bits 0-4, G 5-10, B 11-15).
"""
import sys
import numpy as np
from PIL import Image

def main(src, outdir, target_h=46):
    a = np.array(Image.open(src).convert('RGB')).astype(int)
    key = (a[:, :, 0] > 150) & (a[:, :, 1] < 110) & (a[:, :, 2] > 150) & (abs(a[:, :, 0] - a[:, :, 2]) < 90)
    # dark magenta halo / shadow left under the boots by the generator: also treated as background
    key |= (a[:, :, 0] > 95) & (a[:, :, 1] < 45) & (a[:, :, 2] > 95) & (abs(a[:, :, 0] - a[:, :, 2]) < 75)
    alpha = np.where(key, 0, 255).astype(np.uint8)
    rgb_clean = np.where(key[..., None], 0, a).astype(np.uint8)       # no #FF00FF mixed into the box filter
    full = Image.fromarray(np.dstack([rgb_clean, alpha]), 'RGBA')
    cols = (alpha > 0).any(axis=0)
    segs, st = [], None
    for x, v in enumerate(cols):
        if v and st is None: st = x
        if not v and st is not None:
            if x - st > 40: segs.append((st, x))
            st = None
    if st is not None: segs.append((st, len(cols)))
    assert len(segs) == 6, 'expected 6 frames, found %d' % len(segs)
    crops = []
    for x0, x1 in segs:
        sub = alpha[:, max(0, x0 - 4):x1 + 4]
        ys = np.where(sub.any(axis=1))[0]
        crops.append(full.crop((max(0, x0 - 4), ys[0], x1 + 4, ys[-1] + 1)))
    sc = target_h / crops[0].height
    fr = [c.resize((max(1, round(c.width * sc)), max(1, round(c.height * sc))), Image.BOX) for c in crops]
    cw, ch = max(f.width for f in fr), max(f.height for f in fr)
    sheet = Image.new('RGBA', (cw * 6, ch))
    for i, f in enumerate(fr):
        sheet.paste(f, (i * cw + (cw - f.width) // 2, ch - f.height))
    arr = np.array(sheet)
    mask = arr[:, :, 3] >= 110
    q = Image.fromarray(arr[:, :, :3]).quantize(colors=15, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    idx = np.array(q).astype(np.uint8) + 1
    idx[~mask] = 0
    pal = q.getpalette()[:45]
    def native(r, g, b): return ((r >> 3) & 31) | (((g >> 2) & 63) << 5) | (((b >> 3) & 31) << 11)
    L = ['// tech_art.cpp - pit crew technician pictures (6 frames, 15 colours + transparent), generated by tools/import_technicians.py. Do not edit.',
         '#include "tech_art.h"', '',
         'const uint16_t kTechPal[16] = { 0, ' + ', '.join('0x%04X' % native(*pal[i * 3:i * 3 + 3]) for i in range(15)) + ' };', '',
         'const uint8_t kTechPx[TECH_FRAMES][TECH_W * TECH_H] = {']
    for f in range(6):
        L.append('{')
        for y in range(ch):
            L.append(' ' + ','.join(str(v) for v in idx[y, f * cw:(f + 1) * cw]) + ',')
        L.append('},')
    L.append('};')
    open(outdir + '/tech_art.cpp', 'w').write('\n'.join(L) + '\n')
    open(outdir + '/tech_art.h', 'w').write(
        '// tech_art.h - pit crew technician pictures (see tech_art.cpp)\n#pragma once\n#include <stdint.h>\n'
        'constexpr int TECH_W = %d, TECH_H = %d, TECH_FRAMES = 6;\n'
        '// frames face right, feet on the bottom row\n'
        'enum { TECH_IDLE, TECH_WALK_A, TECH_WALK_B, TECH_WORK, TECH_TYRE, TECH_RAISED };\n'
        'extern const uint16_t kTechPal[16];\nextern const uint8_t kTechPx[TECH_FRAMES][TECH_W * TECH_H];\n' % (cw, ch))
    print('frames', cw, 'x', ch)

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
