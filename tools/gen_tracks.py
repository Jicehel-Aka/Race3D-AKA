#!/usr/bin/env python3
"""gen_tracks.py - rebuild main/game/tracks_data.cpp from tracks/*.trk

Usage (from the project root, any OS):
    python tools/gen_tracks.py          # on Windows you can also use: py tools/gen_tracks.py

Every file in tracks/ is one circuit; they are numbered by file name
(00_..., 01_..., 02_...). The script also updates TRACK_COUNT in main/game/track.h,
so after running it you only have to build the game.

A .trk file is plain text:

    name PALM BAY          circuit name (max 14 letters, A-Z 0-9 space - ')
    theme coast            coast | alpine | city
    music 0                0 Sunset Drive, 1 Summit Rush, 2 Neon Nights
    seed 4242              scenery random seed (change it to reshuffle trees/signs)
    bgseed 77              backdrop random seed (mountains / skyline)
    straight MEDIUM        ...road commands, see docs/CIRCUITS.md
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THEMES = {"coast": "THEME_COAST", "alpine": "THEME_ALPINE", "city": "THEME_CITY"}
COMMANDS = {"straight", "curve", "road", "scurves", "bumps", "downhill"}
KEYS = {"name", "theme", "music", "seed", "bgseed"}
MAX_TRACKS = 16


def fail(path, line, msg):
    sys.exit("%s:%d: %s" % (os.path.relpath(path, ROOT), line, msg))


def parse(path):
    meta = {"theme": "coast", "music": "0", "seed": "1", "bgseed": "1"}
    body = []
    with open(path, encoding="utf-8") as f:
        for n, raw in enumerate(f, 1):
            line = raw.split("#", 1)[0].strip()
            if not line:
                body.append("")
                continue
            word, _, rest = line.partition(" ")
            word_l = word.lower()
            if word_l in KEYS:
                meta[word_l] = rest.strip()
            elif word_l in COMMANDS:
                body.append(line)
            else:
                fail(path, n, "unknown command '%s'" % word)
    if "name" not in meta:
        fail(path, 1, "missing 'name' line")
    name = meta["name"].upper()
    if not re.fullmatch(r"[A-Z0-9 '\-]{1,14}", name):
        fail(path, 1, "name must be 1-14 characters: A-Z 0-9 space ' -")
    theme = meta["theme"].lower()
    if theme.isdigit() and int(theme) < 3:
        theme = ["coast", "alpine", "city"][int(theme)]
    if theme not in THEMES:
        fail(path, 1, "theme must be coast, alpine or city")
    for k in ("music", "seed", "bgseed"):
        if not meta[k].isdigit():
            fail(path, 1, "'%s' must be a whole number" % k)
    if int(meta["music"]) > 2:
        fail(path, 1, "music must be 0, 1 or 2")
    text = "\n".join(body).strip("\n") + "\n"
    if ')TRK"' in text:
        fail(path, 1, "script contains the reserved sequence )TRK\"")
    return name, THEMES[theme], int(meta["music"]), int(meta["seed"]), int(meta["bgseed"]), text


def main():
    tdir = os.path.join(ROOT, "tracks")
    files = sorted(f for f in os.listdir(tdir) if f.endswith(".trk"))
    if not files:
        sys.exit("no .trk file in tracks/")
    if len(files) > MAX_TRACKS:
        sys.exit("too many circuits (%d), the maximum is %d" % (len(files), MAX_TRACKS))
    out = [
        "// tracks_data.cpp - the circuit list.  GENERATED by tools/gen_tracks.py from tracks/*.trk",
        "// Do not edit by hand: edit the .trk files (or use tools/track_editor.html) and run the script again.",
        "#include \"track.h\"",
        "",
        "static_assert(sizeof(g_trackDefs) / sizeof(g_trackDefs[0]) == TRACK_COUNT,",
        "              \"TRACK_COUNT (track.h) must match the number of entries below\");",
        "",
        "const TrackDef g_trackDefs[TRACK_COUNT] = {",
    ]
    for i, fn in enumerate(files):
        name, theme, music, seed, bg, text = parse(os.path.join(tdir, fn))
        out.append("    // ---- %d: %s  (%s)" % (i, name, fn))
        out.append("    { \"%s\", %s, %d, %d, %d, R\"TRK(\n%s)TRK\" }," % (name, theme, music, seed, bg, text))
    out.append("};")
    out.append("")
    data = os.path.join(ROOT, "main", "game", "tracks_data.cpp")
    with open(data, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))

    th = os.path.join(ROOT, "main", "game", "track.h")
    with open(th, encoding="utf-8") as f:
        h = f.read()
    h2, n = re.subn(r"constexpr int TRACK_COUNT = \d+;", "constexpr int TRACK_COUNT = %d;" % len(files), h)
    if n != 1:
        sys.exit("TRACK_COUNT not found in track.h")
    if h2 != h:
        with open(th, "w", encoding="utf-8", newline="\n") as f:
            f.write(h2)
    print("%d circuits written to main/game/tracks_data.cpp (TRACK_COUNT = %d)" % (len(files), len(files)))
    for i, fn in enumerate(files):
        print("  %d  %s" % (i, fn))


if __name__ == "__main__":
    main()
