#!/usr/bin/env python3
"""Imports the roadside scenery sheet (6 rows x 6 columns on a magenta background) into main/game/scen_art.cpp/.h.

Usage:  python3 tools/import_scenery.py tools/scenery_sheet.png main/game
Rows = themes (coast, alpine, city, tropic, glacier, harbour); each sprite gets its own 15-colour palette + transparent.
Needs Pillow, numpy, scipy.  Pixel format = AKA native (R bits 0-4, G 5-10, B 11-15).
"""
import sys
import numpy as np
from PIL import Image
from scipy import ndimage

# name, worldW (world units, road half width = 2000), hitW (solid fraction of worldW), hit kind (1 soft 2 wood 3 rock 4 metal 5 ice 6 heavy)
SPR = [
 ('PARASOL2', 900, .10, 1), ('LIFEGUARD', 800, .55, 2), ('LIGHTHOUSE2', 950, .35, 6), ('SURFRACK', 800, .8, 2), ('FLAMINGO', 700, .25, 1), ('SAILBOAT', 1400, .9, 4),
 ('FIR', 1100, .20, 2), ('CHALET', 2300, .9, 6), ('COW', 800, .8, 1), ('LOGS', 800, .9, 2), ('CROSS', 750, .5, 3), ('PYLON', 1100, .30, 4),
 ('TOWER', 1800, .9, 6), ('NEONSIGN', 1200, .30, 4), ('LAMP2', 560, .10, 4), ('BUSSTOP', 1150, .8, 4), ('TAXI', 760, .9, 4), ('TRAFFICLIGHT', 450, .20, 4),
 ('PALM2', 1400, .18, 2), ('HIBISCUS', 1100, .7, 1), ('TIKIHUT', 1500, .75, 2), ('IDOL', 900, .6, 3), ('BANANA', 1000, .3, 1), ('TORCH', 420, .15, 4),
 ('SNOWFIR', 1100, .20, 2), ('CRYSTAL', 1000, .7, 5), ('SNOWMAN2', 700, .5, 1), ('SNOWROCK', 1300, .85, 3), ('IGLOO', 1500, .85, 5), ('SNOWPOLE', 300, .10, 4),
 ('BLUECONT', 1700, .95, 6), ('REDCONT', 1700, .95, 6), ('CRANE2', 2000, .5, 6), ('BARRELS', 900, .85, 2), ('BOLLARD', 800, .6, 4), ('FISHBOAT', 1500, .9, 4),
]
MAXSIDE = 64
GLOW = {'NEONSIGN': 'bright', 'LAMP2': 'bright', 'TRAFFICLIGHT': 'bright', 'TORCH': 'bright', 'TOWER': 'window'}   # palette entries that ignore ambient light (night)

def main(src, outdir):
    a = np.array(Image.open(src).convert('RGB')).astype(int)
    H, W = a.shape[:2]
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    mag = (r > 110) & (b > 110) & (g < 0.45 * np.minimum(r, b)) & (abs(r - b) < 90)       # magenta-ish background and its darker halo
    lab, nl = ndimage.label(mag)
    border = set(np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))) - {0}
    key = np.isin(lab, list(border))                                                       # only the magenta connected to the picture edge
    key = ndimage.binary_dilation(key, iterations=1) & mag | key
    cw, ch = W / 6.0, H / 6.0
    out = []
    for k in range(36):
        row, col = divmod(k, 6)
        x0, x1, y0, y1 = int(col * cw), int((col + 1) * cw), int(row * ch), int((row + 1) * ch)
        sub = ~key[y0:y1, x0:x1]
        sub = ndimage.binary_opening(sub, iterations=1) | (ndimage.binary_closing(sub, iterations=2) & sub)
        lab2, n2 = ndimage.label(sub)
        if n2 == 0: raise SystemExit('empty cell %d' % k)
        sizes = ndimage.sum(sub, lab2, range(1, n2 + 1))
        keep = np.isin(lab2, [i + 1 for i, s in enumerate(sizes) if s > 0.04 * sizes.max()])   # drop specks, keep detached parts (cables, gondola)
        ys, xs = np.where(keep)
        ya, yb, xa, xb = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
        rgb_ = a[y0:y1, x0:x1][ya:yb, xa:xb].astype(np.uint8)
        al = (keep[ya:yb, xa:xb] * 255).astype(np.uint8)
        rgb_ = np.where(al[..., None] > 0, rgb_, 0).astype(np.uint8)
        im = Image.fromarray(np.dstack([rgb_, al]), 'RGBA')
        sc = MAXSIDE / max(im.width, im.height)
        im = im.resize((max(1, round(im.width * sc)), max(1, round(im.height * sc))), Image.BOX)
        arr = np.array(im)
        mask = arr[..., 3] >= 128
        q = Image.fromarray(arr[..., :3]).quantize(colors=15, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        idx = np.array(q).astype(np.uint8) + 1
        idx[~mask] = 0
        pal = q.getpalette()[:45]
        out.append((idx, pal))
    def native(r_, g_, b_): return ((r_ >> 3) & 31) | (((g_ >> 2) & 63) << 5) | (((b_ >> 3) & 31) << 11)
    L = ['// scen_art.cpp - roadside scenery pictures (36 sprites, 15 colours + transparent each), generated by tools/import_scenery.py. Do not edit.',
         '#include "scen_art.h"', '']
    for k, (idx, pal) in enumerate(out):
        h, w = idx.shape
        L.append('static const uint16_t pal%d[16] = { 0, %s };' % (k, ', '.join('0x%04X' % native(*pal[i * 3:i * 3 + 3]) for i in range(15))))
        L.append('static const uint8_t px%d[%d] = {' % (k, w * h))
        for y in range(h): L.append(' ' + ','.join(str(v) for v in idx[y]) + ',')
        L.append('};')
    L.append('const SceneArt kScene[SCENE_COUNT] = {')
    for k, (idx, pal) in enumerate(out):
        h, w = idx.shape
        n, ww, hw, hk = SPR[k]
        em = 0
        mode = GLOW.get(n)
        for i in range(15):
            cr, cg, cb = pal[i * 3:i * 3 + 3]
            if mode == 'bright' and max(cr, cg, cb) > 190 and (max(cr, cg, cb) - min(cr, cg, cb) > 60 or min(cr, cg, cb) > 200): em |= 1 << (i + 1)
            if mode == 'window' and cr > 190 and cg > 150 and cb < 140: em |= 1 << (i + 1)
        L.append(' { %d, %d, %.1ff, %.2ff, %d, %d, pal%d, px%d },  // %s' % (w, h, ww, hw, hk, em, k, k, n))
    L.append('};')
    open(outdir + '/scen_art.cpp', 'w').write('\n'.join(L) + '\n')
    names = ['SC_' + s[0] for s in SPR]
    open(outdir + '/scen_art.h', 'w').write(
        '// scen_art.h - roadside scenery pictures (see scen_art.cpp). Row = theme, 6 per theme.\n#pragma once\n#include <stdint.h>\n'
        'constexpr int SCENE_COUNT = 36;\n'
        'struct SceneArt { uint8_t w, h; float worldW, hitW; uint8_t hit; uint16_t emissive; const uint16_t* pal; const uint8_t* px; };\n'
        'extern const SceneArt kScene[SCENE_COUNT];\n'
        'enum SceneId {\n  ' + ', '.join(names[i] + (' = 0' if i == 0 else '') for i in range(36)) + '\n};\n')
    print('sizes', [(o[0].shape[1], o[0].shape[0]) for o in out])

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
