#!/usr/bin/env python3
"""Imports hand-made car shadows into main/game/car_shadow_art.cpp.

Usage:  python3 tools/import_car_shadows.py shadow_sheet.png main/game/car_shadow_art.cpp

shadow_sheet.png is the 'voitures_espacees' layout (7 columns x 8 rows, cells of 280x150 px at 1x, the car picture at
x=52 (rear view) / x=28 (wide views), y=24) painted on a flat magenta background (255,0,255) with the shadows drawn in
any dark colour around/under the cars. The picture may be resized: it is scaled back to 1960x1200 and every cell is
re-registered on the car art (tools/unified_3d_car_art.png) so small offsets do not matter.
Only the part of the drawing that is not the car itself and lies below the car's bottom edge is kept.
"""
import sys
import numpy as np
from PIL import Image
from scipy import ndimage

CW, CH, COLS, ROWS = 280, 150, 7, 8
W, W3, H = 176, 224, 84
PX, PY = 52, 24                      # position of the rear picture in a cell

def car_masks(atlas):
    a = np.asarray(Image.open(atlas).convert('RGBA'))[..., 3] > 0
    out = {}
    for d in range(ROWS):
        for s in range(COLS):
            if s == 0: x0, w = 0, W
            else: x0, w = W + (s - 1) * W3, W3
            out[(d, s)] = a[d * H:(d + 1) * H, x0:x0 + w]
    return out

def main():
    sheet, outp = sys.argv[1], sys.argv[2]
    im = Image.open(sheet).convert('RGB').resize((CW * COLS, CH * ROWS), Image.LANCZOS)
    a = np.asarray(im).astype(int)
    key = (np.abs(a[..., 0] - 255) < 110) & (a[..., 1] < 110) & (np.abs(a[..., 2] - 255) < 110)
    user = ~key
    cars = car_masks('tools/unified_3d_car_art.png')
    entries = []; blob = bytearray()
    for d in range(ROWS):
        for s in range(COLS):
            cell = user[d * CH:(d + 1) * CH, s * CW:(s + 1) * CW]
            cm = np.zeros((CH, CW), bool)
            m = cars[(d, s)]
            x0 = PX if s == 0 else PX - (W3 - W) // 2
            cm[PY:PY + H, x0:x0 + m.shape[1]] = m
            best = None
            for dy in range(-14, 15):
                for dx in range(-14, 15):
                    cs = np.roll(np.roll(cm, dy, 0), dx, 1)
                    sc = (cs & cell).sum() - 2 * (cs & ~cell).sum()
                    if best is None or sc > best[0]: best = (sc, dx, dy)
            _, dx, dy = best
            cell = np.roll(np.roll(cell, -dy, 0), -dx, 1)          # register the drawing on the car art
            sh = np.zeros_like(cell)
            ys = np.arange(CH)[:, None]
            for x in range(CW):
                col = np.nonzero(cm[:, x])[0]
                if len(col):
                    sh[:, x] = cell[:, x] & (ys[:, 0] >= col.max() - 3)
                else:
                    sh[:, x] = cell[:, x] & (ys[:, 0] >= PY + 60)
            sh &= ~cm | (ys >= 0)                                   # (the car is drawn over it anyway)
            sh = ndimage.binary_opening(sh, structure=np.ones((2, 2), bool))   # drops 1-pixel lines left by the resize
            lab, n = ndimage.label(sh)
            for i in range(1, n + 1):
                if (lab == i).sum() < 12: sh[lab == i] = False
            body = cm[PY + H * 62 // 100:PY + H * 92 // 100]
            bxs = np.nonzero(body.any(axis=0))[0]
            bc = int((bxs.min() + bxs.max() + 1) // 2 - x0)       # centre of the car body, in picture pixels
            yy, xx = np.nonzero(sh)
            if len(yy) == 0:
                entries.append((0, 0, 0, 0, len(blob), bc)); continue
            bx0, bx1, by0, by1 = xx.min(), xx.max() + 1, yy.min(), yy.max() + 1
            box = sh[by0:by1, bx0:bx1]
            off = len(blob)
            bits = np.packbits(box, axis=1)                           # rows padded to bytes
            blob += bits.tobytes()
            # coordinates relative to the picture's own top-left corner (rear: PX,PY ; wide: PX-24,PY)
            entries.append((int(bx0 - x0), int(by0 - PY), int(box.shape[1]), int(box.shape[0]), off, bc))
    with open(outp, 'w') as f:
        f.write('// car_shadow_art.cpp - generated by tools/import_car_shadows.py from a hand-painted shadow sheet. Do not edit.\n')
        f.write('#include "car_shadow_art.h"\n\n')
        f.write('const uint8_t kCarShadowBits[%d] = {\n' % max(1, len(blob)))
        for i in range(0, len(blob), 24):
            f.write('    ' + ','.join(str(b) for b in blob[i:i + 24]) + ',\n')
        if not blob: f.write('0\n')
        f.write('};\n\n')
        f.write('const CarShadow kCarShadow[CAR_ART_COUNT][CAR_SHADOW_STAGES] = {\n')
        for d in range(ROWS):
            f.write('    {')
            f.write(', '.join('{%d,%d,%d,%d,%d,%d}' % entries[d * COLS + s] for s in range(COLS)))
            f.write('},\n')
        f.write('};\n')
    print('shadows: %d bytes' % len(blob))

main()
