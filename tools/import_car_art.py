#!/usr/bin/env python3
"""Turn a sheet of rear-view car pictures (pink/magenta background) into main/game/car_art.cpp:
one 112x58 palette-indexed sprite (15 colours + transparent) per driver.
usage: import_car_art.py sheet.png out.cpp"""
import sys, numpy as np
from PIL import Image, ImageFilter, ImageEnhance
from scipy import ndimage as ndi

W, H, GROUND = 112, 58, 52
# driver order in race.cpp: VIPER BLAZE NOVA RAVEN ACE ZED KAI YOU -> picture index (row-major in the sheet)
PICK = [(2, 0), (11, 0), (6, 0), (4, 0), (9, 0), (1, 0), (0, 0), (2, 150)]   # (picture, hue shift in degrees)

def cars(path):
    im = Image.open(path).convert('RGB'); a = np.array(im).astype(int)
    R, G, B = a[..., 0], a[..., 1], a[..., 2]
    pink = (R > 165) & (R - G > 45) & (B - G > 10)
    lab, _ = ndi.label(pink)
    border = set(np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))) - {0}
    car = ndi.binary_opening(~np.isin(lab, list(border)), iterations=1)
    lab2, _ = ndi.label(car)
    out = []
    for i, sl in enumerate(ndi.find_objects(lab2)):
        m = lab2[sl] == i + 1
        if m.sum() > 3000: out.append((sl, m))
    out.sort(key=lambda o: (round(o[0][0].start / 100), o[0][1].start))   # row-major
    return im, out

def sprite(im, sl, m, shift=0):
    m = ndi.binary_fill_holes(m)
    m = ndi.binary_erosion(m, iterations=1)
    rgb = np.array(im.crop((sl[1].start, sl[0].start, sl[1].stop, sl[0].stop))).copy()
    rgb[~m] = (10, 8, 14)
    w, h = m.shape[1], m.shape[0]
    cimg = Image.fromarray(rgb).filter(ImageFilter.MedianFilter(5))          # kill the AI-art grain
    cimg = ImageEnhance.Color(cimg).enhance(1.35); cimg = ImageEnhance.Contrast(cimg).enhance(1.18)
    if shift:                                       # recolour the saturated parts (paint) only
        hsv = np.array(cimg.convert('HSV')).astype(int)
        sel = hsv[..., 1] > 90
        hsv[..., 0][sel] = (hsv[..., 0][sel] + int(shift * 256 / 360)) % 256
        cimg = Image.fromarray(hsv.astype('uint8'), 'HSV').convert('RGB')
    rgb = np.array(cimg)
    rgb[~m] = (10, 8, 14)
    nh = max(1, round(h * W / w))
    small = Image.fromarray(rgb).resize((W, nh), Image.LANCZOS)
    msk = Image.fromarray((m * 255).astype('uint8')).resize((W, nh), Image.BOX)
    big = Image.new('RGB', (W, H), (10, 8, 14)); bm = Image.new('L', (W, H), 0)
    top = GROUND - nh
    big.paste(small, (0, top)); bm.paste(msk, (0, top))
    q = big.quantize(colors=15, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[:45]
    idx = np.array(q).astype(np.uint8) + 1
    idx[np.array(bm) < 128] = 0
    cols = [0] + [(pal[3*k] >> 3) | ((pal[3*k+1] >> 2) << 5) | ((pal[3*k+2] >> 3) << 11) for k in range(15)]   # AKA native: R low bits, B high bits
    return idx, cols

def main():
    im, lst = cars(sys.argv[1])
    lst = lst[:12]
    with open(sys.argv[2], 'w') as f:
        f.write('// generated by tools/import_car_art.py - do not edit\n#include "car_art.h"\n')
        f.write('const uint8_t kCarArtPx[%d][%d] = {\n' % (len(PICK), W * H))
        pals = []
        for p, sh in PICK:
            idx, cols = sprite(im, *lst[p], shift=sh); pals.append(cols)
            f.write('{' + ','.join(str(int(v)) for v in idx.ravel()) + '},\n')
        f.write('};\nconst uint16_t kCarArtPal[%d][16] = {\n' % len(PICK))
        for c in pals: f.write('{' + ','.join(str(v) for v in c) + '},\n')
        f.write('};\n')
main()
